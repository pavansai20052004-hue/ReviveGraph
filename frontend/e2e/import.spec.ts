import { test, expect } from '@playwright/test'
import { readFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'

test('CSV errors, preview without writes, atomic import, evidence and compatibility at desktop and 390px', async ({ page, request }) => {
  const consoleErrors: string[] = []
  page.on('pageerror', error => consoleErrors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Recovery overview' })).toBeVisible()
  await expect(page.getByText('Not calculated', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Start synthetic import', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Prepare demo preview' }).click()
  await expect(dialog.getByText('Registered · v1')).toBeVisible()
  await expect(dialog.getByText('Validation passed', { exact: true })).toBeVisible()
  const previewOnly = await (await request.get('/api/v1/state')).json()
  expect(previewOnly.counts.computers).toBe(0)
  expect(previewOnly.counts.components).toBe(0)

  const computerCSV = await readFile(resolve('../datasets/synthetic-v1/computers.csv'))
  const componentCSV = await readFile(resolve('../datasets/synthetic-v1/components.csv'))
  await dialog.getByLabel('Computers CSV', { exact: true }).setInputFiles({ name: 'computers.csv', mimeType: 'text/csv', buffer: computerCSV })
  await dialog.getByLabel('Components CSV', { exact: true }).setInputFiles({ name: 'components.csv', mimeType: 'text/csv', buffer: Buffer.from(componentCSV.toString().replace('RG-PC-01,ram', 'MISSING-PC,ram')) })
  await dialog.getByRole('button', { name: 'Preview both files' }).click()
  await expect(dialog.getByText('LOCATION_NOT_IN_BATCH')).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Commit batch' })).toBeDisabled()

  await dialog.getByRole('button', { name: 'Prepare demo preview' }).click()
  await expect(dialog.getByText('Validation passed', { exact: true })).toBeVisible()
  await expect(dialog.getByText('12 computers · 31 physical component IDs · expected revision 0')).toBeVisible()
  const emptyState = await request.get('/api/v1/state')
  expect((await emptyState.json()).counts.computers).toBe(0)
  await dialog.getByRole('button', { name: 'Commit batch', exact: true }).click()
  await expect(dialog.getByText('Batch committed', { exact: false })).toBeVisible()
  await dialog.getByRole('button', { name: 'View imported inventory' }).click()
  await expect(page.getByRole('tab', { name: 'Computers · 12' })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Components · 31' })).toBeVisible()

  await page.getByRole('button', { name: 'RG-PC-04', exact: true }).click()
  const asset = page.getByRole('region', { name: 'Selected asset details' })
  await expect(asset.getByRole('heading', { name: 'Initial usability: unknown' })).toBeVisible()
  await asset.getByText('Assessment evidence', { exact: true }).click()
  await expect(asset.getByText('2026-10-16 · precision: date', { exact: true })).toBeVisible()
  await expect(asset.getByText('No technician review recorded', { exact: true })).toBeVisible()
  await mkdir(resolve('../docs/implementation-previews'), { recursive: true })
  await page.screenshot({ path: resolve('../docs/implementation-previews/inventory-desktop.png'), fullPage: true })

  await page.getByRole('tab', { name: 'Components · 31' }).click()
  await page.getByRole('button', { name: 'RG-RAM-07', exact: true }).click()
  const part = page.getByRole('region', { name: 'Selected component details' })
  await expect(part.getByText('RG-PC-11', { exact: true })).toHaveCount(2)

  await page.getByRole('link', { name: 'Compatibility Graph', exact: true }).click()
  await page.getByLabel('Target computer', { exact: true }).selectOption('RG-PC-06')
  await page.getByRole('button', { name: 'RG-RAM-11', exact: true }).click()
  const decision = page.getByRole('region', { name: 'Selected compatibility decision' })
  await expect(decision.getByText('RAM_GENERATION', { exact: true })).toBeVisible()
  await page.getByLabel('Target computer', { exact: true }).selectOption('RG-PC-04')
  await page.getByRole('button', { name: 'RG-RAM-04', exact: true }).click()
  await expect(decision.getByText('HEALTH_UNKNOWN', { exact: true })).toBeVisible()
  const configuration = page.getByRole('region', { name: 'Complete configuration inspection' })
  await configuration.getByText('Select RAM modules (0 selected)', { exact: true }).click()
  await configuration.getByRole('checkbox', { name: /RG-RAM-04/ }).check()
  await configuration.getByLabel('Configuration storage').selectOption('RG-SSD-05')
  await configuration.getByRole('button', { name: 'Inspect configuration' }).click()
  await expect(configuration.getByText('HEALTH_UNKNOWN', { exact: true })).toBeVisible()
  let release: () => void = () => {}
  let received: () => void = () => {}
  const responseGate = new Promise<void>(resolve => { release = resolve })
  const requestReady = new Promise<void>(resolve => { received = resolve })
  await page.route('**/api/v1/compatibility/configuration', async route => {
    const response = await route.fetch()
    received()
    await responseGate
    await route.fulfill({ response })
  })
  await configuration.getByRole('button', { name: 'Inspect configuration' }).click()
  await requestReady
  await page.getByLabel('Target computer', { exact: true }).selectOption('RG-PC-06')
  await expect(page.getByText('RG-BOARD-D3-A · v1 · DDR3 UDIMM', { exact: true })).toBeVisible()
  const lateResponse = page.waitForResponse('**/api/v1/compatibility/configuration')
  release()
  await lateResponse
  await expect(configuration.getByText('Configuration blocked', { exact: true })).toHaveCount(0)
  await page.unroute('**/api/v1/compatibility/configuration')
  await page.getByLabel('Target computer', { exact: true }).selectOption('RG-PC-04')
  await page.getByLabel('Eligibility mode', { exact: true }).selectOption('physical')
  await page.getByRole('button', { name: 'RG-RAM-07', exact: true }).click()
  await expect(decision.getByText('SYNTHETIC_PHYSICAL_EXCLUDED', { exact: true })).toBeVisible()
  await page.screenshot({ path: resolve('../docs/implementation-previews/compatibility-desktop.png'), fullPage: true })

  await page.getByRole('link', { name: 'Computer Inventory', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('tab', { name: 'Components · 31' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('link', { name: 'Computer Inventory', exact: true }).click()
  await page.getByRole('button', { name: 'RG-PC-04', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: resolve('../docs/implementation-previews/inventory-mobile.png'), fullPage: true })
  expect(consoleErrors).toEqual([])
})
