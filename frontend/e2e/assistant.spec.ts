import { test, expect } from '@playwright/test'

test('read-only assistant uses a real saved plan and restores its evidence', async ({ page, request }) => {
  test.setTimeout(120000)
  await page.goto('/#dashboard')
  await page.getByRole('button', { name: 'Start synthetic import', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Prepare demo preview' }).click()
  await expect(dialog.getByText('Validation passed', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Commit batch', exact: true }).click()
  await dialog.getByRole('button', { name: 'View imported inventory' }).click()
  await page.getByRole('link', { name: 'Recovery Optimizer', exact: true }).click()
  await page.getByRole('button', { name: 'Calculate plan', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Computed recovery plan' })).toBeVisible({ timeout: 90000 })
  await page.getByRole('link', { name: 'AI Diagnostics', exact: true }).click()
  const assistant = page.getByRole('region', { name: 'Grounded recovery assistant' })
  await expect(assistant.getByRole('button', { name: /Ask Agent/ })).toHaveCount(0)
  await expect(assistant.getByText('Local evidence only - no external AI provider')).toBeVisible()
  await assistant.getByRole('button', { name: 'Read local evidence', exact: true }).click()
  await expect(assistant.getByRole('heading', { name: 'Local evidence summary — no AI request' })).toBeVisible()
  await expect(assistant.getByText(/Physical repair totals remain zero/)).toBeVisible()
  const state = await (await request.get('/api/v1/state')).json()
  expect(state.recovery.physical_passes).toBe(0)
  await page.reload()
  await expect(page.getByRole('region', { name: 'Saved assistant answer' })).toBeVisible()
  await page.getByLabel('Diagnostic asset').selectOption('RG-PC-06')
  await expect(page.getByRole('region', { name: 'Saved assistant answer' })).toHaveCount(0)
  // Hold a real local response, switch asset, then release it: no cross-asset answer.
  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  await page.route('**/plans/*/assistant', async route => {
    const response = await route.fetch()
    await held
    await route.fulfill({ response })
  })
  await assistant.getByRole('button', { name: 'Read local evidence', exact: true }).click()
  await page.getByLabel('Diagnostic asset').selectOption('RG-PC-02')
  release()
  await expect(assistant.getByRole('button', { name: 'Read local evidence', exact: true })).toBeEnabled()
  await expect(page.getByRole('region', { name: 'Saved assistant answer' })).toHaveCount(0)
  await page.unroute('**/plans/*/assistant')
  await assistant.getByRole('button', { name: 'Read local evidence', exact: true }).click()
  await expect(assistant.getByText(/RG-PC-02 uses/)).toBeVisible()
  await page.screenshot({ path: '../data/onsite-assistant-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.getByRole('complementary', { name: 'Primary navigation' }).evaluate(el => el.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
  await expect.poll(() => page.locator('.main-shell').evaluate(el => el.getBoundingClientRect().left)).toBeLessThanOrEqual(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: '../data/onsite-assistant-mobile.png', fullPage: true })
})
