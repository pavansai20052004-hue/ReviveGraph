import { test, expect } from '@playwright/test'

test('explicit CPU provider choice, disabled remote error and preserved local calculation', async ({ page, request }) => {
  test.setTimeout(120000)
  await page.goto('/#dashboard')
  await page.getByRole('button', { name: 'Start synthetic import', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Prepare demo preview' }).click()
  await expect(dialog.getByText('Validation passed', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Commit batch', exact: true }).click()
  await dialog.getByRole('button', { name: 'View imported inventory' }).click()
  await page.getByRole('link', { name: 'Recovery Optimizer', exact: true }).click()
  const execution = page.getByLabel('Calculation execution')
  await expect(execution).toHaveValue('local')
  const orchestration = page.getByLabel('Workflow orchestration')
  await expect(orchestration).toHaveValue('local')
  await orchestration.selectOption('render')
  await page.getByRole('button', { name: 'Calculate plan', exact: true }).click()
  await expect(page.getByText(/RENDER_DISABLED/)).toBeVisible()
  expect((await (await request.get('/api/v1/plans')).json()).items).toHaveLength(0)
  await orchestration.selectOption('local')
  await execution.selectOption('nodus')
  await expect(page.getByText(/No automatic paid retry or local fallback/)).toBeVisible()
  await page.getByRole('button', { name: 'Calculate plan', exact: true }).click()
  await expect(page.getByText(/NODUS_DISABLED/)).toBeVisible()
  expect((await (await request.get('/api/v1/plans')).json()).items).toHaveLength(0)
  await execution.selectOption('local')
  await page.getByRole('button', { name: 'Calculate plan', exact: true }).click()
  const result = page.getByRole('region', { name: 'Computed recovery plan' })
  await expect(result).toBeVisible({ timeout: 90000 })
  await expect(result.getByText(/Local CPU/)).toBeVisible()
  const id = await page.getByLabel('Persisted plan revision').inputValue()
  const plan = await (await request.get(`/api/v1/plans/${id}`)).json()
  expect(plan.execution.provider).toBe('local')
  expect(plan.execution.workflow.orchestrator).toBe('local-pipeline')
  expect(plan.execution.workflow.stages.map((s: { stage: string }) => s.stage)).toEqual(['validate_input', 'execute', 'validate_result', 'generate_audit'])
  expect(['OPTIMAL', 'FEASIBLE']).toContain(plan.result.solver.status)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(execution).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
