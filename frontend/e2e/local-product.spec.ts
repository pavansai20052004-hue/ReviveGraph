import { test, expect } from '@playwright/test'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

test('local synthetic product: authored evidence, interrupted work, reviewed continuation and verification', async ({ page, request }) => {
  test.setTimeout(180000)
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  const external: string[] = []
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (['127.0.0.1', 'localhost'].includes(url.hostname)) return route.continue()
    external.push(url.origin); return route.abort('blockedbyclient')
  })
  const headers = () => ({ 'X-Actor-ID': 'automated-browser-rehearsal', 'Idempotency-Key': crypto.randomUUID() })
  async function post(path: string, data: unknown) {
    const response = await request.post('/api/v1' + path, { headers: headers(), data })
    expect(response.ok(), await response.text()).toBe(true)
    return response.json()
  }
  await page.goto('/#dashboard')
  await page.getByRole('button', { name: 'Start synthetic import', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Prepare demo preview' }).click()
  await expect(dialog.getByText('Validation passed', { exact: true })).toBeVisible()
  expect((await (await request.get('/api/v1/state')).json()).counts.computers).toBe(0)
  await dialog.getByRole('button', { name: 'Commit batch', exact: true }).click()
  await dialog.getByRole('button', { name: 'View imported inventory' }).click()
  await expect(page.getByRole('tab', { name: 'Computers · 12', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Components · 31', exact: true }).click()
  await page.getByRole('button', { name: 'RG-RAM-04', exact: true }).click()
  const editor = page.locator('details[aria-label="Synthetic assessment authoring"]')
  await page.getByText('Assessment history and synthetic authoring', { exact: true }).click()
  await page.getByLabel('Authored synthetic health').selectOption('unknown')
  await page.getByLabel('Authored source', { exact: true }).fill('Automated browser synthetic scenario')
  await page.getByLabel('Synthetic assessment evidence reference').fill('synthetic:automated-browser-assessment')
  await page.getByRole('checkbox', { name: 'I am authoring a synthetic assertion, not a physical assessment.' }).check()
  await page.getByRole('button', { name: 'Save synthetic assessment' }).click()
  await expect(editor.getByText('synthetic:automated-browser-assessment', { exact: false }).first()).toBeVisible()
  const assessment = (await (await request.get('/api/v1/components/RG-RAM-04')).json()).assessment
  expect(assessment.human_reviewed).toBe(false)
  expect(assessment.assessment_kind).toBe('authored_synthetic_assertion')
  const compatibility = await (await request.get('/api/v1/compatibility?target_asset_id=RG-PC-06')).json()
  expect(compatibility.items.find((e: any) => e.component_id === 'RG-RAM-11').hardware.decision).toBe('incompatible')
  await page.getByRole('link', { name: 'Recovery Optimizer', exact: true }).click()
  await page.getByLabel('Simulation execution context').fill('browser-reviewed-continuation')
  await page.getByLabel('Repair budget (INR)', { exact: true }).fill('2500')
  await page.getByLabel('Technician minutes', { exact: true }).fill('330')
  await page.getByRole('button', { name: 'Calculate plan', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Computed recovery plan' })).toBeVisible({ timeout: 90000 })
  const originalId = await page.getByLabel('Persisted plan revision').inputValue()
  const original = await (await request.get(`/api/v1/plans/${originalId}`)).json()
  expect(original.result.baseline.totals).toBeTruthy()
  expect(['OPTIMAL', 'FEASIBLE']).toContain(original.result.solver.status)
  await page.getByRole('button', { name: 'Review approval', exact: true }).click()
  await page.getByRole('checkbox', { name: 'I reviewed this exact revision and authorize simulated work only.' }).check()
  await page.getByRole('button', { name: 'Approve exact simulation plan' }).click()
  await page.getByRole('button', { name: 'Create simulation work orders' }).click()
  await page.getByRole('button', { name: 'Show next available task' }).click()
  const step = page.locator('.focused-work-step')
  for (const checkbox of await step.getByRole('checkbox').all()) await checkbox.check()
  await step.getByRole('textbox').fill('synthetic:automated-browser-initial-preparation')
  await step.getByRole('button', { name: /^Record / }).click()
  await expect(step.getByText('Saved simulation record', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: 'Live Recovery Simulation', exact: true }).click()
  await page.getByText('Simulate another failure', { exact: true }).click()
  const donor = original.result.operations.find((op: any) => op.operation.startsWith('remove_') && op.target_asset_id && op.asset_id !== op.target_asset_id)
  expect(donor).toBeTruthy()
  await page.getByLabel('Failure component').selectOption(donor.component_id)
  await page.getByRole('button', { name: 'Inject failure and replan', exact: true }).click()
  const reconciliation = page.getByRole('region', { name: 'Paused work reconciliation' })
  await expect(reconciliation).toBeVisible()
  await expect(page.getByRole('button', { name: 'Review approval', exact: true })).toBeDisabled()
  await reconciliation.getByLabel('Reconciliation simulation evidence reference').fill('synthetic:automated-browser-reconciliation-review')
  await reconciliation.getByRole('checkbox').check()
  await reconciliation.getByRole('button', { name: 'Calculate reviewed continuation' }).click()
  await expect(page.getByRole('region', { name: 'Continuation resource accounting' })).toBeVisible({ timeout: 90000 })
  const childId = await page.getByLabel('Persisted plan revision').inputValue()
  expect(childId).not.toBe(originalId)
  await expect(page.getByRole('button', { name: 'Create simulation work orders' })).toBeDisabled()
  await page.getByRole('button', { name: 'Review approval', exact: true }).click()
  await page.getByRole('checkbox', { name: 'I reviewed this exact revision and authorize simulated work only.' }).check()
  await page.getByRole('button', { name: 'Approve exact simulation plan' }).click()
  await page.getByRole('button', { name: 'Create simulation work orders' }).click()
  await expect.poll(() => page.getByTestId('work-order').count()).toBeGreaterThan(0)
  const child = await (await request.get(`/api/v1/plans/${childId}`)).json()
  expect(child.parent_plan_id).toBe(originalId)
  expect(child.resource_accounting.cumulative_projected.cost_paise).toBeLessThanOrEqual(250000)
  expect(child.resource_accounting.cumulative_projected.technician_minutes).toBeLessThanOrEqual(330)
  const pending: any[] = child.work_orders.flatMap((o: any) => o.steps.filter((s: any) => s.operation !== 'verify_target').map((s: any) => ({ o, s })))
  const done = new Set<string>()
  while (pending.length) {
    const index = pending.findIndex(({ s }) => s.depends_on.every((id: string) => done.has(id)))
    expect(index).toBeGreaterThanOrEqual(0)
    const { o, s } = pending.splice(index, 1)[0]
    await post(`/work-orders/${o.id}/steps/${s.id}`, { checks: s.required_checks, evidence_ref: `synthetic:automated-browser-residual:${s.id}` })
    done.add(s.id)
  }
  await page.reload()
  const firstOrder = child.work_orders[0]
  const order = page.locator(`#work-order-${firstOrder.id}`)
  await order.locator('summary').click()
  const verification = order.locator('.order-step').filter({ has: page.getByRole('heading', { name: 'Simulated verification', exact: true }) })
  for (const checkbox of await verification.getByRole('checkbox').all()) await checkbox.check()
  await verification.getByRole('textbox').fill('synthetic:automated-browser-continuation-pass')
  await verification.getByRole('button', { name: 'Record simulated verification', exact: true }).click()
  await expect(order.getByText('Simulated verification: pass', { exact: true })).toBeVisible()
  await page.reload()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export audit report', exact: true }).click()
  const download = await downloadEvent
  const report = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(report.history.map((p: any) => p.id)).toContain(originalId)
  expect(report.physical_verified_repairs).toBe(0)
  expect(JSON.stringify(report)).toContain('synthetic:automated-browser-continuation-pass')
  await mkdir(resolve('../data/local-product-review'), { recursive: true })
  await writeFile(resolve('../data/local-product-review/browser-receipt.json'), JSON.stringify({ automated: true, synthetic: true, original: original.result, continued: report.plan.result, accounting: report.plan.resource_accounting, failed_component: donor.component_id, report }, null, 2))
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '../data/local-product-review/continuation-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '../data/local-product-review/continuation-mobile.png' })
  expect(external).toEqual([])
  expect(errors).toEqual([])
})
